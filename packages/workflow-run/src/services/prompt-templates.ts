/** 工具使用提示 */
export function buildToolsHint(): string {
  return `**工具使用**：
前文章节较多，可按需查询：
- list_chapters：列出所有章节
- retrieve_chapter：检索特定章节
- search_content：搜索关键词
- revise_chapter：修订已有章节（解决矛盾）

**⚠️ 矛盾修正机制**：
如果在查阅前文时发现与当前章节存在矛盾（人物设定、时间线、因果关系、逻辑错误等），可以使用 revise_chapter 工具修订前文章节：

**修订时机**：
- ✅ 发现前文与当前情节存在明显矛盾时（优先选择）
- ✅ 前文逻辑不自洽，影响当前章节展开
- ✅ 需要在前文埋下伏笔以支撑当前剧情
- ❌ 不要为了"完美主义"反复修订前文
- ❌ 不要修订超过3章之前的内容（影响范围太大）

**修订原则**：
- 优先修订最近的章节（影响最小）
- 只修订必要的字段（title/summary/content），不需要修改的字段不要传
- 必须说明修订理由（reason 字段）
- 修订完成后立即继续创作当前章节，不要中断

**示例工作流**：
1. 查看前文 → retrieve_chapter 或 search_content
2. 发现矛盾 → 调用 revise_chapter 修订
3. 修订完成 → 继续创作当前章节

**⚠️ 使用约束**：
- 工具调用最多5轮，完成后立即创作
- 直接输出章节内容，不要"我先查看..."等元对话
- 不要返回空响应或思考过程
- 输出必须是完整章节（标题+正文）

**正确示例**：✅ 第十九章：玉简真解\n金光如潮水般退去...
**错误示例**：❌ 我先查看一下前文...（这是思考，不是小说）
`;
}

/** 写作指南（字数分配、原则、自检清单） */
export function buildWritingGuide(wordCount: number): string {
  return `
**核心写作原则**（每个字都必须有存在的理由）：

1. **Show, Don't Tell**（展示，不要讲述）
   ❌ 删除："他明白了...""他感觉到...""他很震惊"
   ✅ 改用：动作、细节、对话

   示例：
   ❌ 李四很生气，他愤怒地看着对方
   ✅ 李四指甲掐进掌心，盯着对方不说话

2. **删除过度装饰**
   ❌ 每10句话最多1个比喻，砍掉无意义的"像...一样"
   ✅ 比喻必须服务于意境或人物，不为装饰而装饰

   示例：
   ❌ 雨下得像掌柜的算盘珠子，一颗一颗砸在瓦上
   ✅ 雨砸在瓦上

3. **对话极简化**
   - 每轮对话≤2句，删除重复信息
   - 删除"他说""他回答""他冷笑道"等提示语
   - 用动作/表情替代提示语

   示例：
   ❌ 钱老板笑着说："押刀。"赵不稳无奈地回答："没带。"
   ✅ 钱老板："押刀。""没带。"

4. **删除解释型插入**
   - 回忆插入≤30字
   - 不在主线高潮时插入解释
   - 删除"现在他明白"式总结

   示例：
   ❌ 他看着掌心那朵缺角梅，忽然想起三年前的事...（200字回忆）
   ✅ 他看着掌心那朵缺角梅，想起三年前有人替他挡过一刀

5. **避免作者讲道理**
   - 删除哲理金句、宣言式结尾
   - 用画面/动作收尾，不用总结

   示例：
   ❌ 江湖从不问你愿不愿意，它只问你还不还得起
   ✅ 赵不稳把手揣进怀里，走进夜色

**内容占比公式**（${wordCount}字分配）：
- 核心冲突：60%（必须在前30%篇幅出现）
- 环境描写：5%（1个核心意象即可）
- 日常对话：10%（每轮≤2句）
- 世界观展示：10%（通过主线展示，不单独解释）
- 人物塑造：10%（3个不同维度的细节）
- 悬念/钩子：5%（结尾留白，不总结）

**扩充字数策略**（从核心向外扩展）：
1. 五感环境（视听触嗅味）
2. 微表情、肢体语言
3. 内心多层思考（表层→深层→联想→决策）
4. 对话中的停顿、试探、迂回

**禁止行为**：
❌ 用"好家伙""震惊""卧槽"反复填充
❌ 场景描写原地重复
❌ 无意义流水账（"他走到门口，打开门，走了出去"）
❌ 过度省略号和感叹号

**元素复用规则**：
如复用前文元素（设定/动作/口头禅/梗），必须版本升级：
- 深化：表面→原因
- 反转：正面→隐藏面
- 后果：动作→影响
- 对比：单一→对照

**人物弧光**（至少满足一项）：
□ 情感变化
□ 认知更新
□ 关系演变
□ 能力/处境变化

**情节推进**（至少满足一项）：
□ 揭示新信息
□ 引入新冲突
□ 改变现状
□ 埋设钩子

**自检清单**（写完必检查）：
□ 存在性：这句删掉会损失什么？若无，删
□ 装饰性：这个比喻必须吗？换成直接描述会更好吗？
□ 节奏性：能压缩到一半吗？
□ 展示性：是在"告诉"还是"展示"？
□ 逻辑性：角色行为符合设定和动机吗？

**输出格式**：
- title: 章节标题（简洁有力）
- summary: 章节简介（20-50字）
- content: 章节正文（${wordCount}字，±10%，仅正文，不含标题简介）
- clues（可选）：伏笔列表
- resolvedClueIds（可选）：回填的伏笔ID

**记住：简约即优雅，删除即完美。读者需要的是流畅、紧凑、有冲击力的故事。**
`;
}

/** 第一章特殊要求提示 */
export function buildFirstChapterHint(): string {
  return `

**第一章特殊要求**：
- 核心冲突必须在前30%出现
- 世界观通过具体事件展现，不用旁白说明
- 人物通过行动和对话展现，避免"他是个xxx的人"
- 前1/3设置吸引读者的悬念或冲突
- 通过叙述节奏、用词风格确立整部作品基调`;
}

/** 前文章节回顾提示 */
export function buildPreviousContext(chapters: ChapterData[], useTools: boolean): string {
  if (useTools) {
    return '**章节总览**（使用工具查询详细内容）：\n' +
      chapters.map(ch => `- 第${ch.chapterNumber}章：${ch.title}（${ch.summary}）`).join('\n');
  }

  const recentChapters = chapters.slice(-3);
  const olderChapters = chapters.slice(0, -3);
  let context = '';

  if (olderChapters.length > 0) {
    context += '**早期章节**（仅标题）：\n';
    context += olderChapters.map(ch => `- 第${ch.chapterNumber}章：${ch.title}`).join('\n');
    context += '\n\n';
  }

  if (recentChapters.length > 0) {
    context += '**近期章节**（详细回顾）：\n\n';
    context += recentChapters.map(ch => {
      const preview = ch.content.substring(0, 400);
      return `## 第 ${ch.chapterNumber} 章：${ch.title}

**简介**：${ch.summary}

**关键情节**（前400字）：
${preview}${ch.content.length > 400 ? '...' : ''}
`;
    }).join('\n\n');
  }

  return context;
}
