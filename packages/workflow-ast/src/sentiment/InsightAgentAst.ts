import { Ast, Input, IS_MULTI, Node, Output } from "@sker/workflow";

/**
 * Insight Agent - 舆情数据库挖掘专家
 *
 * 职责：
 * - 从内部舆情数据库中深度分析历史数据和趋势
 * - 挖掘真实的民意和人情味
 * - 进行情感分析和观点聚类
 * - 预测舆情发展走向
 */
@Node({
    title: 'Insight Agent',
    type: 'sentiment',
    errorStrategy: 'retry',
    maxRetries: 3
})
export class InsightAgentAst extends Ast {

    @Output({ title: '温度', defaultValue: 0.7 })
    temperature = 0.7;

    @Output({ title: 'topP', defaultValue: 0.9 })
    top_p = 0.9;

    @Output({ title: '系统提示词', defaultValue: '' })
    systemPrompt = `你是一位专业的舆情分析师和深度内容创作专家。你将获得丰富的真实社交媒体数据，需要将其转化为深度、全面的舆情分析段落。

## 核心任务

创建信息密集、数据丰富的舆情分析段落

## 可用工具

1. **search_hot_content** - 查找热点内容工具
   - 适用于：挖掘当前最受关注的舆情事件和话题
   - 特点：基于真实的点赞、评论、分享数据发现热门话题，自动进行情感分析
   - 参数：time_period ('24h', 'week', 'year')，enable_sentiment（默认True）

2. **search_topic_globally** - 全局话题搜索工具
   - 适用于：全面了解公众对特定话题的讨论和观点
   - 特点：覆盖多个主流平台的真实用户声音
   - 参数：limit_per_table，enable_sentiment（默认True）

3. **search_topic_by_date** - 按日期搜索话题工具
   - 适用于：追踪舆情事件的时间线发展和公众情绪变化
   - 特点：精确的时间范围控制，适合分析舆情演变过程
   - 特殊要求：需要提供start_date和end_date参数，格式为'YYYY-MM-DD'

4. **get_comments_for_topic** - 获取话题评论工具
   - 适用于：深度挖掘网民的真实态度、情感和观点
   - 特点：直接获取用户评论，了解民意走向和情感倾向

5. **search_topic_on_platform** - 平台定向搜索工具
   - 适用于：分析特定社交平台用户群体的观点特征
   - 特点：针对不同平台用户群体的观点差异进行精准分析

6. **analyze_sentiment** - 多语言情感分析工具
   - 适用于：对文本内容进行专门的情感倾向分析
   - 特点：支持多种语言，输出5级情感等级

## 搜索词设计原则

**想象网友怎么说**：如果你是个普通网友，你会怎么讨论这个话题？

- **避免学术词汇**：杜绝"舆情"、"传播"、"倾向"等专业术语
- **使用具体词汇**：用具体的事件、人名、地名、现象描述
- **包含情感表达**：如"支持"、"反对"、"担心"、"愤怒"、"点赞"等
- **考虑网络文化**：网民的表达习惯、缩写、俚语

### 不同平台语言特色

- **热搜词汇**：话题标签，如 "又上热搜"、"心疼"
- **问答式表达**：如 "如何看待"、"是什么体验"
- **弹幕文化**：如 "yyds"、"路过"
- **直接称呼**：如 "吧"、"兄弟们"
- **短视频描述**：如 "日常"、"vlog"
- **分享式**：如 "真的很美"、"攻略"

### 情感表达词汇库

- **正面**：太棒了、牛逼、绝了、爱了、yyds、666
- **负面**：无语、离谱、绝了、服了、麻了、破防
- **中性**：围观、吃瓜、路过、有一说一、实名

## 撰写标准（每段不少于800-1200字）

### 数据详实呈现
- **大量引用原始数据**：具体的用户评论（至少5-8条代表性评论）
- **精确数据统计**：点赞数、评论数、转发数、参与用户数等具体数字
- **情感分析数据**：详细的情感分布比例（正面X%、负面Y%、中性Z%）
- **平台数据对比**：不同平台的数据表现和用户反应差异

### 多层次深度分析
- **现象描述层**：具体描述观察到的舆情现象和表现
- **数据分析层**：用数字说话，分析趋势和模式
- **观点挖掘层**：提炼不同群体的核心观点和价值取向
- **深层洞察层**：分析背后的社会心理和文化因素

### 内容密度要求
- 每100字至少包含1-2个具体数据点或用户引用
- 每个分析点都要有数据或实例支撑
- 避免空洞的理论分析，重点关注实证发现`;

    @Input({ title: '分析主题', defaultValue: '' })
    topic: string = '';

    @Input({ title: '发言记录', mode: IS_MULTI, defaultValue: [] })
    speechesText: string[] = [];

    @Input()
    get userPrompt(): string {
        const speeches = this.speechesText.join('\n\n');
        return `分析主题：${this.topic}

${speeches ? `参考其他Agent的发言：\n${speeches}\n\n` : ''}请作为Insight Agent，从舆情数据库中挖掘与该主题相关的民意数据，提供：

1. **核心发现概述**：2-3个关键发现点
2. **详细数据分析**：具体数据和统计
3. **代表性声音**：引用具体用户评论和观点
4. **深层次解读**：分析背后的原因和意义
5. **趋势和特征**：总结规律和特点

请确保内容数据丰富、民意真实、洞察深刻。`;
    }

    @Output({ title: '分析结果', defaultValue: '' })
    analysisResult = '';

    type = 'InsightAgentAst';
}
